"""Murmur external authenticator backed by Raven's user database (or LDAP).

Murmur calls ``authenticate`` over ZeroC Ice. The return convention is the Slice one: a user id
(>= 0) to accept, -1 to reject, -2 to fall through to Murmur's own database.
"""

import os

import Ice

Ice.loadSlice("", ["-I" + Ice.getSliceDir(), os.path.join(os.path.dirname(os.path.abspath(__file__)), "Murmur.ice")])

import Murmur  # noqa: E402  (generated by loadSlice above)

ACCEPT_FALLTHROUGH = -2
REJECT = -1


class MumbleAuthenticator(Murmur.ServerUpdatingAuthenticator):
    def __init__(self, app, logger, ice):
        Murmur.ServerUpdatingAuthenticator.__init__(self)
        self.app = app
        self.logger = logger
        self.ice = ice

    def authenticate(self, name, pw, certificates, certhash, certstrong, current=None):
        if name == "SuperUser":
            return ACCEPT_FALLTHROUGH, None, None

        try:
            with self.app.app_context():
                user = self.app.security.datastore.find_user(username=name)
                if user is None or not user.active:
                    return REJECT, None, None

                if self.app.config.get("RAVEN_ENABLE_LDAP"):
                    return self._ldap_authenticate(user, name, pw)

                from flask_security.utils import verify_password

                if verify_password(pw, user.password):
                    return user.id, user.username, None
                return REJECT, None, None
        except Exception as e:  # noqa: BLE001
            self.logger.error("Mumble authentication failed for {}: {}".format(name, e))
            return REJECT, None, None

    def _ldap_authenticate(self, user, name, pw):
        from flask_ldap3_login import AuthenticationResponseStatus

        from raven.extensions import ldap_manager

        result = ldap_manager.authenticate(name, pw)
        if result.status != AuthenticationResponseStatus.success:
            return REJECT, None, None

        from raven.blueprints.raven_api.ldap_api import save_user

        save_user(result.user_dn, result.user_id, result.user_info, result.user_groups)
        return user.id, user.username, None

    def getInfo(self, id, current=None):
        return False, None

    # The remaining operations are not supported; answer with Murmur's "fall through" values so
    # Murmur uses its own database instead of receiving a value Ice cannot marshal.

    def nameToId(self, name, current=None):
        return ACCEPT_FALLTHROUGH

    def idToName(self, id, current=None):
        return ""

    def idToTexture(self, id, current=None):
        return b""

    def registerUser(self, info, current=None):
        return ACCEPT_FALLTHROUGH

    def unregisterUser(self, id, current=None):
        return ACCEPT_FALLTHROUGH

    def getRegisteredUsers(self, filter, current=None):
        return {}

    def setInfo(self, id, info, current=None):
        return ACCEPT_FALLTHROUGH

    def setTexture(self, id, tex, current=None):
        return ACCEPT_FALLTHROUGH
